package mc.GTedd.cn.gtshaders.ui;

/**
 * 面板能停在哪。
 *
 * <p>刻意<b>不</b>做成可任意嵌套的区域树（那种能把一个区反复对半劈开的结构）。
 * 树能表达的布局确实更多，代价是每次拖动都要重算整棵树、每个节点都要存分割比例，
 * 而实际上没人会把一个着色器编辑器劈成八块。三个停靠边 + 浮动已经覆盖了
 * 「我想把版本记录挪到底下去看」这类真实需求，实现量却只有树的几分之一。
 *
 * <p>真需要「左栏上下各放一块」的那天，加一个 {@code LEFT_BOTTOM} 常量即可，
 * 不必推翻现有结构。
 */
public enum DockZone {

    /** 屏幕左侧竖栏。 */
    LEFT,
    /** 屏幕右侧竖栏。 */
    RIGHT,
    /** 画布下方的横栏。放版本记录、管线这类「宽比高有用」的内容很合适。 */
    BOTTOM,
    /** 脱离停靠、自己飘着的窗口。 */
    FLOATING;

    /** 是不是贴边停靠的那三个（相对于浮动）。 */
    public boolean isDocked() {
        return this != FLOATING;
    }
}
